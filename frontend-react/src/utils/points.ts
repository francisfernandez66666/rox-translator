import { fmtInt } from '../lib/format'

/** 积分数值 → 千分位字符串（非法值显示 0）
 *  ★ 〇-Q：千分位按界面语种（原写死 'en-US'，德语界面下应是 1.234 而非 1,234） */
export function fmtPoints(points: number): string {
  return fmtInt(points)
}
