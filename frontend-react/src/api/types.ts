/**
 * Any —— 后端 JSON 出参的宽松承接别名。
 * 历史上有 11 处 `type Any = Record<string, any>` 逐文件重复定义；现统一从此处导入。
 * 用法：`const r: Any = await someApi()`，随后按 `r.xxx as string/number` 收窄。
 */
export type Any = Record<string, any>
