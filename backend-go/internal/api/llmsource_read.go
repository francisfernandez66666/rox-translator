// ============ llmsource_read.go · 职责说明 ============
// api 包读取"这一台此刻生效的上游模型配置"的唯一入口（★ 2026-10-04 〇-AR 第 5 波）。
//
// 为什么单独成文件：管理台模型页、/api/health 的状态词、试用留痕、用量回退档
// 过去各自读 `s.Cfg` 的那份**开机快照**，而翻译引擎读的是另一处——
// 同一个"现在用的是哪把 Key"在四个面上有四个时刻的读数。
// ㊻ 的现网形态正是这么长出来的：运营在管理台配好了 Key，另一台实例
// 带着启动期的随机占位 Key 一直 401，而健康检查与看板都"看着正常"。
// 现在四个读点一律走本文件的 liveLLM，与 `Engine.liveLLM` 共用 internal/llmsource 那一把尺子。
//
// 三条口径（都在 llmsource 文件头钉着，这里只复述与本层相关的两条）：
//  1. 探测是**惰性＋节流**的（默认 5 秒 TTL ＋ sha256 指纹），不是每个请求读一次库；
//     所以健康检查被监控系统打爆也不会变成读库风暴。
//  2. 无库形态（单测／纯配置文件启动）只按本进程配置现值算一份，**不碰全局指针**——
//     全局快照会被同进程其他用例发布，拿它当"这台生效的配置"会让断言归因到别人家的用例。
//
// =============================================
package api

import (
	"context"

	"translator/internal/llmsource"
)

// liveLLM 返回本进程此刻生效的上游模型配置快照（**永不 nil**，调用方不写判空）。
// 参数 ctx: 请求上下文，只用于热加载日志带 trace_id，探测本身与请求无关。
// 两条分支（有库惰性重探／无库只读现值）的口径收在 llmsource.Current 里，本层不再抄一遍。
func (s *Server) liveLLM(ctx context.Context) *llmsource.Snapshot {
	return llmsource.Current(ctx, s.Store, s.Cfg)
}
