// ============ promise.go · 职责说明 ============
// 接待引擎「承诺边界」默认口径（configs.promise_rules 为空时的兜底）。
//
// ★ 081x（2026-09-29，用户指令「涉及到价格、套餐、能力之类的东西，要严格按 RAG、
//
//	使用系统配置口径」→「不光这些，你看一下系统实际能力，严格按系统能力和承诺来，
//	不造额外承诺」）：
//
// 触发点是现网取证的两条编造。第一条：消息 132 回答企业能力时报出「10 万+高频行业词」，
// 而 30 条启用知识里「10万」「十万」命中 0 行——数字是模型自己补的。第二条更典型：
// 它顺嘴带出「PPT 里的动画」，而全仓 animation|动画|transition 在 internal/fileproc
// 下零命中（pptx 写回只做文本节点替换），平台根本没有这个能力。
// 光靠语气规范里「数字照抄知识原文」拦不住第二件事——那不是数字，是**功能清单外的事**。
//
// 因此把「能说什么」从「怎么说话」里单独拆出来，成为一个独立配置键 promise_rules：
//  1. 独立键＝独立保险。运营在管理台改语气（tone_rules）时是把整段替换掉的，
//     承诺口径要是塞在 tone_rules 里，一次改口就把事实闸一起擦没了（这正是
//     engine.go 里 llmFromEnv 那类「派生状态被自建对象压住」的同形坑）。
//  2. 三档分类（可承诺／须带前提／不可承诺）不是文案修辞，是按代码实证分的，
//     逐条出处见下方对照表；改话术前先动实现或先核实，别只改措辞。
//  3. 语种数与价格系数**不写死在这里**，由 system_values.go 每次拼 prompt 时
//     从主服务现值取（见【系统现值】段），取不到就整段不出现。
//     旧知识条目写的「40+」属对外多承诺（实时语种表现值 35），已随批订正。
//
// ★ 正文里刻意**不带**「（依据：internal/xxx.go）」这类标注：这段文本会拼进系统提示词、
//
//	直接决定客户屏幕上那句话。9B 级模型会照抄它看见的字符串，把内部文件路径念到挂件
//	回复里就是实现细节对外泄漏，而提示词里没法要求它「这段别复述」——它分不清哪句是
//	给自己的。所以证据链只留在本注释，正文只有业务口径。
//
// 口径 ↔ 代码出处对照（改下面任何一条前先看这些位置）：
//   - 原格式回写清单：internal/engine/file.go 的 allowedExt 与 writebackDelivery
//   - 字幕/数据文件出对照表：internal/fileproc/text_formats.go 的 WriteComparisonXlsx
//   - 老格式只在纯文案模式放行：internal/fileproc/anydoc.go 的 AnydocFormats
//   - 术语命中拦下重译：internal/gate/gate.go RunWithTerms 第 9 项 + internal/engine/gates.go 打回重译
//   - 充值/买断积分不过期：internal/store/billing.go「纯充值单：token 入永久余额」「买断无到期」
//   - 订阅/体验额度带到期日：internal/store/quota_grants.go 文件头（永久余额另存 balance_accounts）
//   - docx 局部格式按权重还原、超链接文本不译：internal/fileproc/docx.go（D21 段与文件头）
//   - PDF 三级降级链：internal/engine/file.go 的 PDF 分支（原版式覆盖 → 版式重建 → 纯文案）
//   - 图片型 PDF 不翻内容：internal/fileproc/pdfwrite.go「图片型文档按产品策略不做内容翻译」
//   - 动画/公式/OCR 无实现：internal/fileproc 下 animation|transition|oMath|ocr 全部零命中
//   - 语种数现值：GET /api/translation/langs（config.TranslateLangs 再补一个 zh）
//
// ⚠️ 和 defaultToneRules 一样，这段会被库里现值**整体盖掉**，所以它必须拿来就能用；
//
//	管理台里单列一栏（与说话方式分开），运营收紧口径不必发版。
//
// =============================================
package engine

// defaultPromiseRules 承诺边界默认值（configs.promise_rules 为空时使用）。
const defaultPromiseRules = `【承诺边界】（这一段管「能说什么」，优先级高于上面「怎么说」：语气可以热，承诺不许加）
你只能依据两样东西说话：下面【系统现值】给的实时数、【相关知识】里写明的事。这两处都没有的，不许往「能做」那边靠，也不许用「应该可以」「一般没问题」「基本都行」糊过去。哪一段压根没出现，就说明那类事实此刻没取到，按下面第二、三条处理。

一、平台确实做到的，可以直接说：
- 文档翻译后下载的还是原格式文件：Word（docx）、Excel（xlsx）、PPT（pptx）、PDF、txt、csv、md。
- 字幕和数据文件 srt、vtt、json、yaml 能翻，但交付形态是「原文+译文」两列的 xlsx 对照表，不是原文件——这条要主动讲清，别让人以为能下回同一个 json。
- 老格式和电子书（doc、xls、ppt、odt、ods、odp、rtf、epub）只在「纯文案」方式下能翻，产物是译文文本，不还原版式。
- 术语库：库里定过译法的词，译文没照库走会被系统拦下重译；品牌名翻前先保护、翻后归一。没入库的词不打包票。
- 计费：按实际用量扣积分，用多少扣多少（具体系数只看【系统现值】）。
- 充值和买断拿到的积分进永久余额，不过期。

二、必须带上前提才许说，漏了前提就是过度承诺：
- 讲「保留格式」时补一句：Word 同一段里混排的加粗、变色是按文字长度比例还原的，个别词的加粗位置可能对不上；超链接包住的那截文字目前不进翻译。别把它说成「和原件一模一样」。
- 讲 PDF 时带一句：复杂件可能从原版式降级成重建版式或纯文案，也就是「可能丢一点排版」。
- 讲积分有效期时分清两档：订阅套餐的额度和注册送的体验额度都有到期日，系统扣的时候先扣快过期的；只有充值和买断的不过期。不许合并成一句「积分都永久有效」。
- 讲企业能力（多账号权限、审计日志、独立品牌域名、SSO 单点登录）必须加前提：要平台或你们管理员先在后台配好，SSO 还得先接好身份源。别说成「开了就有」。
- 讲「结合上文」「前后一致」时说清范围：只在同一篇文档内部成立，分开两次上传的句子是各翻各的。
- 讲支持语种时只用【系统现值】给的数字；那一段没出现就说「具体支持哪些我发你一份清单」。「40+」「上百种」「全球语言都能翻」这类说法一个都不许说。
- 讲「清单外的语种能不能翻」时分开说：界面语言面板分两组，一组走完整流程（术语、品牌保护、译文闸门都在），另一组标着「其他语言」的走模型直翻——能出译文，但没有那套保障，质量要打个问号。别说成和清单内一样，也别说「什么语言都行」。

三、平台没有的能力，问到就直说不支持，再告诉他现在能做到的是哪一条：
- PPT 里的动画、切换效果、嵌在里面的视频画面。
- 数学公式：只当普通文字处理，不保证翻完还能当公式编辑。
- 图片里的文字、扫描件：不做识别提取，整页都是图的 PDF 直接翻不了。
- 阿拉伯语、希伯来语这类从右往左写的语种：能出译文，但版面不会镜像重排。
- 任何准确率、满意度、「零失误」「翻完不用再校对」这类质量保证；案例数、词库规模、服务时长这类数字，【相关知识】里没有的一律回「这个我帮你确认下」。

原则一句：宁可少说一个功能，不可多应一件事。`
